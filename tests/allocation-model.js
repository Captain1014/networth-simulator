function runAllocationModelTests({ assert, near, equal, throws, base, account, flow, sim }) {
  function reserves(s, emergency = 0, earmark = 0) {
    s.finance.cashReserves = { USD: { emergencyAmount: emergency, earmarkAmount: earmark },
      KRW: { emergencyAmount: 0, earmarkAmount: 0 } };
  }
  function allocation(s, a, extra = {}) {
    const rule = NWFinanceState.newRecord('allocations');
    Object.assign(rule, { name: 'Synthetic allocation', enabled: true, status: 'confirmed',
      accountId: a.id, percentPct: 100, ...extra });
    s.finance.allocations.push(rule);
    return rule;
  }
  let s = base(); s.finance.useDetailedFlows = true; reserves(s);
  let a = account(s, 'taxable', 0);
  flow(s, 'salary', 100, { start: '2030-01-01' });
  let rule = allocation(s, a);
  let r = sim(s);
  near(r.rows[0].autoInvested, 1200, 'All new surplus is invested when explicitly configured');
  near(r.rows[0].invest, 0, 'Automatic investment debits cash');
  near(r.rows[0].accSnapshot[0].balance, 1200, 'Automatic investment credits brokerage once');
  near(r.rows[0].accSnapshot[0].costBasis, 1200, 'Automatic purchases raise pooled cost basis');
  near(r.rows[0].netWorth, 1200, 'Cash-to-brokerage allocation conserves wealth');
  near(r.rows[0].income, 1200, 'Automatic purchases do not fabricate income');
  near(r.rows[0].taxes, 0, 'Purchases do not create realized-gain tax');
  near(r.rows[0].savings, 0, 'Cash surplus subtracts automatic investment transfers');
  equal(r.meta.journal.filter(x => x.kind === 'automatic-investment').length, 12, 'One monthly allocation settlement');
  const original = JSON.stringify(s); sim(s);
  equal(JSON.stringify(s), original, 'Allocation simulation preserves original native inputs');
  rule.percentPct = 50; r = sim(s);
  near(r.rows[0].autoInvested, 600, 'Percentage applies to new surplus, not all accumulated cash');
  near(r.rows[0].invest, 600, 'Unallocated cash is not swept again next month');
  s.money.investAsset.USD = '5000'; r = sim(s);
  near(r.rows[0].autoInvested, 600, 'Opening cash is not new investable earnings');
  near(r.rows[0].invest, 5600, 'Opening wealth remains intact without an explicit sweep');
  s.money.investAsset.USD = ''; rule.percentPct = 100; reserves(s, 600, 300); r = sim(s);
  near(r.rows[0].autoInvested, 300, 'Emergency and additional earmark targets fill before investing');
  near(r.rows[0].invest, 900, 'Protected cash stays in its source currency');
  near(r.rows[0].protectedCash, 900, 'Protected cash is a subset of bank cash');
  near(r.rows[0].netWorth, 1200, 'Protection does not create an extra asset');
  near(r.rows[0].freeAvailable, 300, 'Free financial assets subtract the full protection target');
  near(r.rows[0].reserveShortfall, 0, 'Satisfied reserve target has no funding gap');
  reserves(s, 2000, 0); r = sim(s);
  near(r.rows[0].autoInvested, 0, 'Unfilled reserves block automatic investment');
  near(r.rows[0].reserveShortfall, 800, 'Reserve shortage is reported, not hidden');
  near(r.rows[0].freeAvailable, 0, 'Unfunded protection goals are not discretionary funds');
  s.finance.cashReserves.USD.emergencyAmount = null; r = sim(s);
  near(r.rows[0].autoInvested, 0, 'Unknown reserve is not silently treated as zero');
  equal(r.rows[0].freeAvailable, null, 'Free-funds conclusion remains unknown until both currency targets entered');
  assert(r.meta.warnings.some(x => x.includes('Automatic investment paused')), 'Incomplete enabled allocation warns explicitly');
  reserves(s); rule.percentPct = null;
  near(sim(s).rows[0].autoInvested, 0, 'Unknown investment percentage pauses investing');
  rule.percentPct = 100; rule.accountId = null;
  near(sim(s).rows[0].autoInvested, 0, 'Missing destination pauses investing without losing cash');
  rule.accountId = a.id; rule.enabled = false;
  near(sim(s).rows[0].autoInvested, 0, 'Disabled allocation does not invest');
  rule.enabled = true; rule.start = '2030-01-01'; rule.end = '2030-03-01';
  near(sim(s).rows[0].autoInvested, 200, 'Allocation end is exclusive and month-end settlement based');
  const sc = NWFinanceState.newRecord('scenarios');
  Object.assign(sc, { name: 'Synthetic switch', enabled: false, status: 'confirmed' });
  s.finance.scenarios.push(sc); rule.scenarioId = sc.id;
  near(sim(s).rows[0].autoInvested, 0, 'Disabled allocation scenario excludes transfers');
  sc.enabled = true; sc.start = '2030-02-01';
  near(sim(s).rows[0].autoInvested, 100, 'Allocation scenario window controls settlements');
  rule.scenarioId = ''; rule.start = ''; rule.end = ''; rule.status = 'estimated'; s.finance.model.includeTentative = false;
  near(sim(s).rows[0].autoInvested, 0, 'Tentative allocations respect global inclusion switch');
  rule.status = 'confirmed';
  s.finance.allocations.push({ ...rule, id: crypto.randomUUID() });
  throws(() => NWCore.validate(s), 'Overlapping enabled rules cannot spend the same currency surplus twice');
  s.finance.allocations.pop(); rule.percentPct = 101;
  throws(() => NWCore.validate(s), 'Allocation percentage above 100 rejected');
  rule.percentPct = 100;
  const locked = account(s, 'roth', 0); rule.accountId = locked.id;
  throws(() => NWCore.validate(s), 'Automatic surplus destination must be a brokerage, not locked retirement');
  rule.accountId = a.id;
  s.finance.accounts[a.id].owner = 'partner';
  near(sim(s).rows[0].autoInvested, 0, 'Excluded partner destination cannot consume self cash');
  s.finance.accounts[a.id].owner = 'self';
  s = base(); reserves(s); a = account(s, 'taxable', 0); allocation(s, a);
  s.money.investAsset.USD = '500'; s.money.rentalDepositAsset.USD = '500';
  s.events.push({ id: 1, type: 'deposit-return', currency: 'USD', date: '2030-06-01', value: '500', name: 'Synthetic refund' });
  r = sim(s);
  near(r.rows[0].autoInvested, 0, 'Deposit refund and opening principal are not new savings');
  near(r.rows[0].invest, 1000, 'Returned deposit remains cash without new earned surplus');
  s.events = [{ id: 1, type: 'lumpsum-in', currency: 'USD', date: '2030-06-01', value: '500', drainAccountId: a.id, name: 'Synthetic asset transfer' }];
  a.balance = '500'; s.finance.accounts[a.id].costBasis = 500; r = sim(s);
  near(r.rows[0].autoInvested, 0, 'Existing brokerage withdrawal does not trigger reinvestment');
  s = base(); s.finance.useDetailedFlows = true; reserves(s);
  a = account(s, 'taxable', 0); allocation(s, a, { percentPct: 50 });
  flow(s, 'salary', 1000); flow(s, 'expense', 200);
  const manual = account(s, 'roth', 0, { contribSelf: '1200' });
  r = sim(s);
  near(r.rows[0].employeeContributions, 1200, 'Legacy account contributions still settle first');
  near(r.rows[0].autoInvested, 4200, 'Only surplus after expenses and existing contributions is allocated');
  near(r.rows[0].netWorth, 9600, 'Manual plus automatic transfers do not add extra wealth');
  const payroll = s.finance.flows[0];
  const espp = NWFinanceState.newRecord('espp');
  Object.assign(espp, { name: 'Synthetic allocation ESPP', status: 'confirmed', start: '2030-01-01',
    eligibleAnnualPay: 12000, contribPct: 5, payrollSourceId: payroll.id, ruleConfirmed: true, taxPct: 0 });
  s.finance.espp.push(espp); r = sim(s);
  near(r.rows[0].autoInvested, 3900, 'ESPP payroll principal is deducted before allocating remaining surplus');
  near(r.rows[0].esppClearing, 600, 'Automatic investment does not sweep employee-owned ESPP clearing');
  near(r.rows[0].netWorth, 9600, 'ESPP principal and automatic investments are transfers, not extra income');
  s.finance.espp = [];
  s.finance.flows[1].amount = 2000; r = sim(s);
  near(r.rows[0].autoInvested, 0, 'Negative operating surplus never triggers investment');
  assert(r.rows[0].shortfall > 0, 'Underfunded living needs remain a failure');
  s = base(); reserves(s); s.finance.useDetailedFlows = true;
  a = account(s, 'taxable', 1000); allocation(s, a);
  flow(s, 'expense', 100, { frequency: 'once', start: '2030-01-10' });
  flow(s, 'salary', 500, { frequency: 'once', start: '2030-01-20' });
  r = sim(s);
  near(r.rows[0].autoInvested, 0, 'A withdrawal earlier in the same month prevents sell-and-buy churn');
  near(r.rows[0].invest, 500, 'Later paycheck is not silently used to buy back withdrawn shares');
  s = base(); reserves(s); s.finance.useDetailedFlows = true;
  a = account(s, 'taxable', 0); allocation(s, a);
  flow(s, 'salary', 100, { currency: 'USD' }); flow(s, 'salary', 200000, { currency: 'KRW' });
  allocation(s, a, { currency: 'KRW' }); r = sim(s);
  near(r.rows[0].autoInvested, 2400, 'Independent source currencies share no duplicated global surplus');
  near(r.rows[0].accSnapshot[0].costBasis, 2400, 'Cross-currency purchases convert once and carry basis');
  equal(s.finance.flows[1].amount, 200000, 'Native KRW input amount remains unchanged');
  s = base('2030-12-15'); reserves(s); s.finance.useDetailedFlows = true;
  a = account(s, 'taxable', 0); allocation(s, a); flow(s, 'salary', 310);
  near(sim(s).rows[0].autoInvested, 170, 'Partial first month invests only actually accrued net income');
  s = base(); reserves(s); s.finance.useDetailedFlows = true; s.inputs.retireAge = '40';
  a = account(s, 'taxable', 0); allocation(s, a); flow(s, 'other', 100);
  near(sim(s).rows[0].autoInvested, 1200, 'Allocation dates are independent of account employment/contribution cutoff');
  s = base(); reserves(s); s.finance.useDetailedFlows = true;
  a = account(s, 'taxable', 0, { rate: '12' }); allocation(s, a); flow(s, 'salary', 100);
  r = sim(s);
  let expected = 0;
  for (let month = 0; month < 12; month++) expected += 100 * Math.pow(1.12,
    (Date.UTC(2031, 0, 1) - Date.UTC(2030, month + 1, 1)) / 86400000 / 365);
  near(r.rows[0].accSnapshot[0].balance, expected, 'Purchased shares earn returns only after their month-end purchase');
  const mc = NWFinanceEngine.monteCarlo(s, { runs: 3, horizonAge: 40, seed: 'allocation-parity' });
  near(mc.p50[0], r.rows[0].netWorth, 'Zero-volatility Monte Carlo and Base use the same allocation ledger');
  const legacy = structuredClone(s); legacy.finance.version = 2;
  delete legacy.finance.allocations; delete legacy.finance.cashReserves; delete legacy.finance.planningItems; delete legacy.finance.comparisons;
  const migrated = NWCore.validate(legacy);
  equal(migrated.schemaVersion, 3, 'Allocation upgrade keeps root schema three');
  equal(migrated.finance.version, 3, 'Finance schema two upgrades to three');
  equal(migrated.finance.allocations, [], 'Old profile does not invent an investment instruction');
  equal(migrated.finance.cashReserves.USD.emergencyAmount, null, 'Old profile has unknown, not verified-zero reserves');
  equal(NWCore.validate(s).finance.allocations, s.finance.allocations, 'Allocation configuration survives validation round trip');
  s = base(); s.finance.useDetailedFlows = true; reserves(s);
  const business = flow(s, 'business', 100, { start: '2030-01-01', taxTreatment: 'gross', taxPct: 0 });
  const comparison = NWFinanceState.newRecord('comparisons');
  Object.assign(comparison, { name: 'Synthetic replacement', enabled: true, status: 'confirmed',
    sourceFlowId: business.id, amount: 250, start: '2030-07-01', businessCost: 50, taxPct: 20 });
  s.finance.comparisons.push(comparison);
  const before = JSON.stringify(s);
  near(sim(s).rows[0].income, 1200, 'Configured comparison never adds revenue to base income');
  let compared = NWFinanceEngine.compareFlow(s, comparison.id, { horizonAge: 40 });
  assert(compared.ready, 'Complete manual replacement comparison can run');
  near(compared.result.rows[0].income, 1560, 'Six months baseline then replacement profit; not two simultaneous businesses');
  equal(JSON.stringify(s), before, 'Comparison does not mutate the base profile');
  comparison.start = '2030-01-01';
  near(NWFinanceEngine.compareFlow(s, comparison.id, { horizonAge: 40 }).result.rows[0].income, 1920, 'Same-start replacement safely disables original without duplicate income');
  comparison.businessCost = null;
  assert(!NWFinanceEngine.compareFlow(s, comparison.id).ready, 'Unknown business costs prevent a supposedly complete comparison');
  const item = NWFinanceState.newRecord('planningItems');
  Object.assign(item, { name: 'Synthetic review', referenceGroup: 'flows', referenceId: business.id, amount: 999, reviewConfirmed: false });
  s.finance.planningItems.push(item); r = sim(s);
  assert(r.meta.planning[0].recordPresent && r.meta.planning[0].included && !r.meta.planning[0].ready, 'Recorded, included and reviewed are independent plan states');
  near(r.rows[0].income, 1200, 'Planning note amounts never become extra income');
  item.reviewConfirmed = true;
  assert(sim(s).meta.planning[0].ready, 'Reviewed complete linked inputs can be marked ready');
  business.businessCost = null;
  assert(!sim(s).meta.planning[0].ready, 'Review checkbox cannot hide missing required inputs');
  item.referenceId = 'missing-record';
  throws(() => NWCore.validate(s), 'Invalid planning links rejected before save');
}
