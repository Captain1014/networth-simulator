async function runFinanceUiTests({ assert, equal, near }) {
  const state = NWCore.emptyState();
  state.projectionStartDate = '2030-01-01';
  state.fx = { base: 'USD', quote: 'KRW', rate: 2000, date: NWCore.today(), fetchedAt: new Date().toISOString(), source: 'manual' };
  Object.assign(state.inputs, { currentAge: '40', retireAge: '70', returnRate: '0', returnVolatility: '0', inflation: '0', wageGrowthRate: '0' });
  state.money.investAsset.USD = '1000';
  state.money.annualIncome.USD = '12000';
  state.money.annualExpense.USD = '6000';
  state.accounts = [{ id: 1, type: 'taxable', currency: 'USD', balance: '500', rate: '0', name: 'Synthetic broker' }];
  for (const c of ['USD', 'KRW']) state.finance.cash[c] = { ratePct: 0, interestTaxPct: 0, confirmed: true };
  applyWorkspaceState(state); renderAll();
  const initial = simulate()[0].netWorth;
  window.confirm = () => true;
  openFinanceSettings();
  assert(document.querySelector('#financeModal [role="dialog"]'), 'Finance editor has accessible dialog semantics');
  function change(id, value) {
    const el = document.getElementById(id);
    if (!el) throw new Error('Missing finance input: ' + id);
    if (el.type === 'checkbox') el.checked = value;
    else el.value = String(value);
    el.dispatchEvent(new Event('change', { bubbles: true }));
  }
  change('finance-cash-USD-ratePct', 4);
  equal(Number(W.state.finance.cash.USD.ratePct), 4, 'Cash return edited through form');
  flushStateSave();
  change('finance-cash-USD-ratePct', 3);
  equal(Number(W.state.finance.cash.USD.ratePct), 3, 'Open form edits current object after autosave replacement');
  change('finance-cash-USD-ratePct', 0);
  financeToggleDetailed(true);
  assert(W.state.finance.useDetailedFlows && W.state.finance.legacyEventsArchived, 'Detailed conversion preserves legacy fields without counting twice');
  near(simulate()[0].netWorth, initial, 'Detailed conversion preserves the full-year budget result');
  assert(document.getElementById('annualIncome').closest('.field').classList.contains('finance-legacy-inactive'), 'Detailed mode marks legacy annual input inactive');
  addFinanceRecord('flows', 'expense');
  let index = W.state.finance.flows.length - 1;
  change(`finance-flows-${index}-name`, 'Synthetic pet budget');
  change(`finance-flows-${index}-amount`, 50);
  change(`finance-flows-${index}-frequency`, 'monthly');
  change(`finance-flows-${index}-start`, '2030-01-01');
  change(`finance-flows-${index}-status`, 'confirmed');
  near(simulate()[0].expense, 6600, 'New monthly expense form uses one monthly amount, not an annual duplicate');
  const flowId = W.state.finance.flows[index].id;
  assert([...document.querySelectorAll('#eventTimeline .event-timeline-name')].some(x => x.textContent.includes('Synthetic pet budget')), 'Detailed cash-flow records appear in timeline');
  addFinanceRecord('scenarios');
  const scenarioIndex = W.state.finance.scenarios.length - 1;
  change(`finance-scenarios-${scenarioIndex}-name`, 'Synthetic optional scenario');
  change(`finance-scenarios-${scenarioIndex}-start`, '2032-01-01');
  renderFinanceForm();
  change(`finance-flows-${index}-scenarioId`, W.state.finance.scenarios[scenarioIndex].id);
  near(simulate()[0].expense, 6000, 'Scenario-linked flow does not apply before its date');
  removeFinanceRecord('scenarios', scenarioIndex);
  assert(!W.state.finance.scenarios[scenarioIndex].enabled, 'Removing a linked scenario disables it without silently activating flows');
  assert(W.state.finance.flows.some(x => x.id === flowId), 'Linked record survives scenario disable');
  removeFinanceRecord('flows', index);
  change('finance-accounts-1-costBasis', 500);
  change('finance-accounts-1-capitalGainsTaxPct', 20);
  change('finance-accounts-1-dividendTaxPct', 0);
  change('finance-accounts-1-taxConfirmed', true);
  addFinanceRecord('rsu');
  const grant = W.state.finance.rsu[0];
  change('finance-rsu-0-grantTotal', 100);
  change('finance-rsu-0-accountId', 1);
  change('finance-rsu-0-taxPct', 20);
  change('finance-rsu-0-status', 'confirmed');
  document.querySelector(`#finance-record-${grant.id} .finance-schedule > button`).click();
  change('finance-rsu-0-schedule-0-date', '2030-03-01');
  change('finance-rsu-0-schedule-0-amount', 100);
  near(simulate()[0].netWorth, initial + 80, 'RSU form adds only net stock once');
  addFinanceRecord('dbBenefits');
  assert(!W.state.finance.dbBenefits[0].enabled, 'DB form defaults to excluded, not an invented benefit');
  assert(document.getElementById('finance-db-help'), 'DB editor explains manual estimates and existing-asset transfers');
  change('finance-dbBenefits-0-name', 'Synthetic DB payout');
  change('finance-dbBenefits-0-currency', 'USD');
  change('finance-dbBenefits-0-paymentDate', '2030-12-31');
  change('finance-dbBenefits-0-expectedAmount', 1000);
  change('finance-dbBenefits-0-effectiveTaxPct', 20);
  change('finance-dbBenefits-0-status', 'confirmed');
  change('finance-dbBenefits-0-enabled', true);
  near(simulate()[0].netWorth, initial + 80, 'New DB requires separate-entitlement acknowledgement');
  change('finance-dbBenefits-0-separateEntitlementConfirmed', true);
  near(simulate()[0].netWorth, initial + 880, 'Dedicated DB inputs settle net benefit once');
  equal(document.getElementById('finance-dbBenefits-0-sourceAccountId').tagName, 'SELECT', 'DB source uses named retirement selector');
  assert(![...document.getElementById('finance-dbBenefits-0-destinationAccountId').options].some(x => x.value === '1'), 'DB retirement destination excludes brokerage accounts');
  assert([...document.querySelectorAll('#eventTimeline .event-timeline-name')].some(x => x.textContent.includes('Synthetic DB payout')), 'DB appears on chronological timeline');
  flushStateSave();
  const storedDb = JSON.parse(W.store.storage.getItem(NWCore.KEY)).finance.dbBenefits;
  equal(storedDb, getStateForExport().finance.dbBenefits, 'Autosave preserves dedicated DB fields');
  const backup = getStateForExport();
  const encrypted = await encryptData('synthetic-db-test-password', await gzipCompressUtf8(JSON.stringify(backup)));
  const restored = NWCore.validate(await backupCipherToState('synthetic-db-test-password', encrypted));
  equal(restored.finance.dbBenefits, backup.finance.dbBenefits, 'DB fields survive compressed encrypted backup round trip');
  near(NWFinanceEngine.simulate(restored).rows[0].netWorth, simulate()[0].netWorth, 'Restored DB profile produces identical forecast');
  change('finance-dbBenefits-0-scenarioId', W.state.finance.scenarios[scenarioIndex].id);
  near(simulate()[0].netWorth, initial + 80, 'DB linked to disabled scenario is excluded');
  removeFinanceRecord('scenarios', scenarioIndex);
  assert(W.state.finance.scenarios.some(x => x.id === W.state.finance.dbBenefits[0].scenarioId), 'Deleting DB-linked scenario preserves reference by disabling it');
  change('finance-dbBenefits-0-scenarioId', '');
  change('finance-dbBenefits-0-amountBasis', 'net');
  near(simulate()[0].netWorth, initial + 1080, 'DB net-input form does not apply tax again');
  assert(document.getElementById('financeFormError').textContent === '', 'Valid finance settings show no form error');
  closeFinanceSettings();
  assert(!document.querySelector('.app').inert, 'Closing finance dialog restores background interaction');
  W.state.finance.model.runs = 4;
  W.state.finance.model.seed = 'ui-worker-test';
  setChartMode('montecarlo');
  await runMonteCarloUI();
  assert(mcResult && mcResult.runs === 4 && mcResult.seed === 'ui-worker-test', 'Web Worker uses the same finance settings and reproducible seed');
  assert(!document.getElementById('btnRunMC').disabled, 'Monte Carlo worker restores run button');
  openFinanceSettings();
  change('finance-dbBenefits-0-expectedAmount', 1100);
  assert(mcResult === null && !document.getElementById('mcStale').hidden, 'Editing DB settings invalidates prior Monte Carlo results');
  closeFinanceSettings();
  const profile = getStateForExport();
  profile.money.investAsset.USD = '2000';
  const transfer = new DataTransfer();
  transfer.items.add(new File([JSON.stringify(profile)], 'synthetic-private-profile.json', { type: 'application/json' }));
  const file = document.getElementById('privateFinanceFile');
  file.files = transfer.files;
  await importPrivateFinanceFile(file);
  equal(document.getElementById('investAsset').value, '2000', 'Private profile file replaces only after normal import validation/confirmation');
  equal(getStateForExport().finance.rsu[0].schedule[0].amount, 100, 'Private import retains finance schedule data');
  equal(getStateForExport().finance.dbBenefits[0].expectedAmount, 1100, 'Private import retains DB data');
  addAccount({ type: 'irp_kr', name: 'Synthetic receiving IRP', balance: '0' });
  const irpId = accounts.at(-1).id;
  addAccount({ type: 'dc_kr', name: 'Synthetic source DC', balance: '1000' });
  const dcId = accounts.at(-1).id;
  openFinanceSettings();
  change('finance-dbBenefits-0-treatment', 'existing_account_transfer');
  change('finance-dbBenefits-0-sourceAccountId', dcId);
  change('finance-dbBenefits-0-destinationAccountId', irpId);
  change('finance-dbBenefits-0-settlement', 'retirement_account');
  change('finance-dbBenefits-0-expectedAmount', 300);
  let settled = simulate()[0];
  near(settled.accSnapshot.find(x => x.id === dcId).balance, 700, 'DB source selector debits actual DC account');
  near(settled.accSnapshot.find(x => x.id === irpId).balance, 300, 'DB destination selector credits actual IRP account');
  closeFinanceSettings();
  removeAccount(dcId);
  assert(getStateForExport().finance.dbBenefits[0].sourceAccountId === null, 'Deleting DB source clears its reference without corrupting profile');
  undoDelete();
  equal(getStateForExport().finance.dbBenefits[0].sourceAccountId, dcId, 'Undo restores DB account link with its account');
  addEvent({ type: 'lumpsum-in', name: 'Synthetic old DB event', date: '2030-12-31', value: '300' });
  const eventId = events[0].id;
  openFinanceSettings();
  change('finance-dbBenefits-0-replacesEventId', eventId);
  equal(getStateForExport().finance.dbBenefits[0].replacesEventId, eventId, 'DB replacement uses named existing event selector');
  closeFinanceSettings();
  removeEvent(eventId);
  assert(getStateForExport().finance.dbBenefits[0].replacesEventId === null, 'Deleting old payout clears DB event reference');
  openFinanceSettings();
  addFinanceRecord('flows', 'other');
  const replacementIndex = W.state.finance.flows.length - 1;
  change(`finance-flows-${replacementIndex}-frequency`, 'once');
  change(`finance-flows-${replacementIndex}-amount`, 300);
  change(`finance-flows-${replacementIndex}-start`, '2030-12-31');
  const replacementId = W.state.finance.flows[replacementIndex].id;
  renderFinanceForm();
  change('finance-dbBenefits-0-replacesFlowId', replacementId);
  equal(getStateForExport().finance.dbBenefits[0].replacesFlowId, replacementId, 'DB replacement uses existing one-time income selector');
  removeFinanceRecord('flows', replacementIndex);
  equal(getStateForExport().finance.dbBenefits[0].replacesFlowId, '', 'Deleting old income clears DB flow reference');
  closeFinanceSettings();
}
